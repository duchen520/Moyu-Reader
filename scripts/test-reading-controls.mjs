import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { setTimeout as delay } from 'node:timers/promises';

const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '1498', '--strictPort'], { stdio: 'ignore' });
let browser, passed = 0;
const errors = [];
const check = text => { passed++; console.log('PASS ' + text); };
try {
  for (let i = 0; i < 100; i++) { try { if ((await fetch('http://127.0.0.1:1498')).ok) break; } catch {} await delay(100); }
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 820 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    const content = Array.from({ length: 90 }, (_, i) => `第${i + 1}段：${'用于验证按住暂停、松开继续与目录定位的本机测试文字。'.repeat(5)}`).join('\n\n');
    localStorage.setItem('tomato-reader-v01:books', JSON.stringify([{ id: 'controls', title: '阅读操作测试', author: '本机测试', description: '', source: 'local', coverStyle: 0, addedAt: 1,
      chapters: Array.from({ length: 200 }, (_, i) => ({ id: 'control-' + i, title: `第${i + 1}章 目录定位`, content, loaded: true })) }]));
    localStorage.setItem('tomato-reader-v01:progress', JSON.stringify({ controls: { chapterIndex: 147, scrollRatio: .2, paragraphIndex: 10, updatedAt: 1 } }));
  });
  await page.goto('http://127.0.0.1:1498');
  await page.getByRole('button', { name: '阅读 阅读操作测试', exact: true }).click();
  await page.locator('.story-content p').first().waitFor();
  const centered = async () => page.waitForFunction(() => {
    const list = document.querySelector('.chapter-scroll');
    if (!list) return false;
    const row = list.querySelector('.chapter-item.current').getBoundingClientRect(), bounds = list.getBoundingClientRect();
    return row.top >= bounds.top && row.bottom <= bounds.bottom && Math.abs((row.top + row.bottom - bounds.top - bounds.bottom) / 2) < 3;
  }, undefined, { timeout: 3000 }).then(() => true);
  assert.match(await page.locator('.chapter-item.current').textContent(), /第148章/);
  assert.ok(await centered());
  check('Saved chapter 148 is centered in the directory on initial opening');
  const paperBefore = await page.locator('.reading-canvas').evaluate(el => el.scrollTop);
  await page.getByRole('button', { name: '收起目录', exact: true }).click();
  assert.equal(await page.locator('.chapters-list').count(), 0);
  await page.getByRole('button', { name: '展开目录', exact: true }).click();
  assert.ok(await centered());
  assert.equal(await page.locator('.reading-canvas').evaluate(el => el.scrollTop), paperBefore);
  await page.locator('.chapter-scroll').evaluate(el => el.scrollTop = 0);
  await page.getByTitle('章节目录', { exact: true }).click();
  await page.getByRole('button', { name: '展开目录', exact: true }).click();
  assert.ok(await centered());
  check('Directory collapse and both reopen paths restore the current chapter without scrolling the reading body');
  await page.getByTitle('听书与自动翻页').click();
  await page.getByRole('button', { name: '自动阅读', exact: true }).click();
  await page.getByRole('button', { name: '平滑滚动', exact: true }).click();
  await page.getByRole('button', { name: '收起面板', exact: true }).click();
  await page.waitForTimeout(400);
  const box = await page.locator('.reading-canvas').boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + 150);
  await page.mouse.down();
  const held = await page.locator('.reading-canvas').evaluate(el => el.scrollTop);
  await page.waitForTimeout(550);
  assert.equal(await page.locator('.reading-canvas').evaluate(el => el.scrollTop), held);
  await page.getByText('按住左键，自动阅读暂缓中', { exact: true }).waitFor();
  await page.mouse.up();
  await page.waitForTimeout(350);
  const resumed = await page.locator('.reading-canvas').evaluate(el => el.scrollTop);
  assert.ok(resumed > held && resumed < held + 20);
  check('Holding the actual left mouse button freezes scrolling; release resumes without catching up');
  await page.mouse.down();
  await page.locator('.reading-canvas').evaluate(el => el.scrollTop += 180);
  const moved = await page.locator('.reading-canvas').evaluate(el => el.scrollTop);
  await page.waitForTimeout(250);
  assert.equal(await page.locator('.reading-canvas').evaluate(el => el.scrollTop), moved);
  await page.mouse.up();
  await page.waitForTimeout(300);
  const adjusted = await page.locator('.reading-canvas').evaluate(el => el.scrollTop);
  assert.ok(adjusted > moved && adjusted < moved + 20);
  check('Manual repositioning while held resumes from the new position');
  await page.mouse.down();
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await page.mouse.up();
  const lostRelease = await page.locator('.reading-canvas').evaluate(el => el.scrollTop);
  await page.waitForTimeout(250);
  assert.ok(await page.locator('.reading-canvas').evaluate(el => el.scrollTop) > lostRelease);
  check('Losing the pointer release outside the window does not leave automatic reading stuck');
  await page.mouse.down();
  await page.locator('.audio-mini-pill').getByTitle('停止', { exact: true }).evaluate(el => el.click());
  await page.mouse.up();
  const stopped = await page.locator('.reading-canvas').evaluate(el => el.scrollTop);
  await page.waitForTimeout(250);
  assert.equal(await page.locator('.reading-canvas').evaluate(el => el.scrollTop), stopped);
  check('Releasing the mouse never restarts automatic reading after explicitly stopping');
  await page.getByTitle('听书与自动翻页').click();
  await page.getByRole('button', { name: '定时翻页', exact: true }).click();
  await page.getByLabel('翻页间隔').fill('3');
  const pageBox = await page.locator('.reading-canvas').boundingBox();
  await page.mouse.move(pageBox.x + pageBox.width / 2, pageBox.y + Math.min(100, pageBox.height / 2));
  await page.mouse.down();
  const pageHeld = await page.locator('.reading-canvas').evaluate(el => el.scrollTop);
  await page.waitForTimeout(3400);
  assert.equal(await page.locator('.reading-canvas').evaluate(el => el.scrollTop), pageHeld);
  await page.mouse.up();
  await page.waitForTimeout(400);
  assert.equal(await page.locator('.reading-canvas').evaluate(el => el.scrollTop), pageHeld);
  await page.waitForTimeout(3100);
  assert.ok(await page.locator('.reading-canvas').evaluate(el => el.scrollTop) > pageHeld + 10);
  await page.getByRole('button', { name: '停止自动阅读', exact: true }).click();
  check('Holding freezes the page-turn countdown; release continues the remaining interval');
  await page.getByRole('button', { name: '平滑滚动', exact: true }).click();
  await page.locator('.reading-canvas').evaluate(el => el.scrollTop = el.scrollHeight);
  await page.mouse.down();
  await page.waitForTimeout(1800);
  assert.match(await page.locator('.page-paper h1').textContent(), /第148章/);
  await page.mouse.up();
  await page.locator('.page-paper h1').filter({ hasText: '第149章' }).waitFor({ timeout: 5000 });
  await page.getByRole('button', { name: '停止自动阅读', exact: true }).click();
  assert.ok(await centered());
  check('Holding at the chapter end prevents automatic chapter changes; the next current chapter is centered');
  await page.getByRole('button', { name: '收起面板', exact: true }).click();
  await page.setViewportSize({ width: 900, height: 640 });
  await page.getByTitle('阅读设置', { exact: true }).click();
  assert.ok(await page.locator('.chapters-list').isHidden());
  await page.getByRole('button', { name: '关闭阅读偏好', exact: true }).click();
  assert.ok(await centered());
  assert.ok(await page.locator('.reader-layout').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await mkdir('test-output', { recursive: true });
  await page.screenshot({ path: 'test-output/reading-controls-900.png' });
  assert.deepEqual(errors, []);
  check('Current directory position survives narrow-window panel changes with no runtime errors');
  console.log(`${passed} reading controls checks passed (local book only).`);
} finally { await browser?.close(); server.kill(); }
