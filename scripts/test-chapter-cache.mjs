import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const code = ts.transpileModule(await readFile('src/lib/chapterCache.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { limitChapterCache, focusChapterCache, touchChapterCache, CHAPTER_CACHE_LIMIT, CHAPTER_CACHE_BYTES } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
const book = (id, source, chapters = 120, size = 1200) => ({ id, source, chapters: Array.from({ length: chapters }, (_, i) => ({ id: id + i, title: 'Chapter ' + i, content: '文'.repeat(size), loaded: true, paragraphIds: [0], itemVersion: '1' })) });
let passed = 0; const check = text => { passed++; console.log('PASS ' + text); };
const local = book('local', 'local', 120), official = book('official', 'official');
focusChapterCache('official', 80);
const result = limitChapterCache([local, official]);
assert.equal(result[0], local); assert.equal(result[1].chapters.length, 120);
assert.equal(result[1].chapters.filter(c => c.content).length, CHAPTER_CACHE_LIMIT);
for (let i = 78; i <= 82; i++) assert.ok(result[1].chapters[i].content);
const evicted = result[1].chapters.find(c => !c.content); assert.equal(evicted.loaded, false); assert.equal(evicted.paragraphIds, undefined);
check('Official bodies are bounded while full local books, catalog entries and the current five-chapter window remain intact');
focusChapterCache(null, 0);
const large = book('large', 'official', 100, 600000);
const limited = limitChapterCache([large]);
assert.ok(limited[0].chapters.reduce((n, c) => n + c.content.length * 2 + (c.paragraphIds?.length ?? 0) * 8, 0) <= CHAPTER_CACHE_BYTES);
check('A byte limit also bounds unusually long chapters outside the active window');
const a = book('a', 'official', 20), b = book('b', 'official', 20);
touchChapterCache('a', 'a19');
const global = limitChapterCache([a, b]);
assert.equal(global.flatMap(book => book.chapters).filter(c => c.content).length, CHAPTER_CACHE_LIMIT);
assert.ok(global[0].chapters[19].content);
check('The count is global across books and keeps recently used chapter text');
focusChapterCache('huge', 3);
const protectedBook = limitChapterCache([book('huge', 'official', 10, 1000000)])[0];
assert.deepEqual(protectedBook.chapters.flatMap((c, i) => c.content ? [i] : []), [1, 2, 3, 4, 5]);
check('The active reading window wins over the byte budget without retaining unrelated huge chapters');
console.log(`${passed} cache checks passed.`);
